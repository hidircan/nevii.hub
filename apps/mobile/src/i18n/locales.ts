export const STRINGS: Record<Locale, Strings> = { tr, en };

/** Nokta-yollu anahtar → metin. Eksik anahtar önce Türkçe'ye, o da yoksa anahtarın kendisine düşer. */
export function lookup(locale: Locale, path: string): string {
  const from = (root: Strings): unknown => path.split(".").reduce<unknown>((acc, part) => {
    if (acc !== null && typeof acc === "object" && part in (acc as Record<string, unknown>)) {
      return (acc as Record<string, unknown>)[part];
    }
    return undefined;
  }, root);
  const hit = from(STRINGS[locale]);
  if (typeof hit === "string") return hit;
  const fallback = from(STRINGS.tr);
  if (typeof fallback === "string") return fallback;
  return path;
}

/** `{ad}` yer tutucularını değerlerle doldurur. */
export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    vars[name] === undefined ? m : String(vars[name]),
  );
}

/** Sözlükteki tüm yaprak yollar (testler ve araçlar için). */
export function allPaths(root: Strings = STRINGS.tr): string[] {
  const out: string[] = [];
  const walk = (node: unknown, prefix: string) => {
    if (typeof node === "string") {
      out.push(prefix);
      return;
    }
    if (node !== null && typeof node === "object") {
      for (const [k, v] of Object.entries(node as Record<string, unknown>)) {
        walk(v, prefix ? `${prefix}.${k}` : k);
      }
    }
  };
  walk(root, "");
  return out;
}
