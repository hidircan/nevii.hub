export function isFeatureFlagKey(value: string): value is FeatureFlagKey {
  return (FEATURE_FLAGS as readonly string[]).includes(value);
}

export const FEATURE_DISABLED_MESSAGE = "Bu modül bu kurum için kapalı.";

export function moduleDisabledResult(flag: FeatureFlagKey): ServiceResult<never> {
  return fail("FORBIDDEN", FEATURE_DISABLED_MESSAGE, { feature: flag });
}

export function featureOk(): ServiceResult<true> {
  return ok(true);
}
